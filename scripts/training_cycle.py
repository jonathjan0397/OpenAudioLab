#!/usr/bin/env python3
"""Real-hardware artist-training cycle (milestone 5 gate evidence).

Generates a small custom-track dataset through the public API, freezes it,
runs a budgeted LoRA optimization on the real engine, evaluates the candidate
with fixed prompts and activates it. Stdlib only.
"""

from __future__ import annotations

import json
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

RUN = uuid.uuid4().hex[:8]

BASE = os.environ.get("OAL_BASE_URL", "http://127.0.0.1:50555").rstrip("/")
API = f"{BASE}/api/v1"
TOKEN = os.environ.get("OAL_TRAIN_TOKEN", "training-cycle-token")

LYRICS = [
    "[Verse]\nFreight train hum on a steel guitar\n[Chorus]\nRide, ride, into the sun\n",
    "[Verse]\nNeon rain on a downtown street\n[Chorus]\nStay, stay till the morning light\n",
    "[Verse]\nDust and gold on a two-lane road\n[Chorus]\nDrive, drive where the wild winds blow\n",
]
PROMPT = "Jangly country rock, male vocal, warm and bright."


def request(method: str, path: str, body=None, headers: dict[str, str] | None = None, raw: bool = False):
    url = path if path.startswith("http") else (f"{BASE}{path}" if path.startswith("/api") else f"{API}{path}")
    data = None
    hdrs = {"Authorization": f"Bearer {TOKEN}", **(headers or {})}
    if isinstance(body, (bytes, bytearray)):
        data = body
    elif body is not None:
        data = json.dumps(body).encode("utf-8")
        hdrs.setdefault("Content-Type", "application/json")
    req = urllib.request.Request(url, data=data, headers=hdrs, method=method)
    try:
        with urllib.request.urlopen(req, timeout=1800) as resp:
            payload = resp.read()
            return resp.status, (payload if raw else json.loads(payload or b"{}")), dict(resp.headers)
    except urllib.error.HTTPError as exc:
        payload = exc.read()
        if raw:
            return exc.code, payload, dict(exc.headers)
        try:
            return exc.code, json.loads(payload or b"{}"), dict(exc.headers)
        except json.JSONDecodeError:
            return exc.code, {"raw": payload[:200].decode("utf-8", "replace")}, dict(exc.headers)


def check(label: str, condition: bool, detail: str = "") -> None:
    print(f"{'PASS' if condition else 'FAIL'}  {label}  {detail}")
    if not condition:
        sys.exit(1)


def wait(job_id: str, label: str, timeout: float) -> dict:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        _, detail, _ = request("GET", f"/jobs/{job_id}")
        if detail["status"] in ("succeeded", "failed", "cancelled"):
            check(f"{label} terminal", detail["status"] == "succeeded", detail.get("error_code") or "")
            return detail
        time.sleep(3)
    raise SystemExit(f"{label} timed out")


def main() -> None:
    print(f"OpenAudioLab training cycle against {BASE}")

    asset_ids = []
    for index, lyrics in enumerate(LYRICS):
        status, accepted, _ = request("POST", "/jobs", {
            "operation": "music.generate", "model_id": "ace-step-1.5", "music_description": PROMPT,
            "lyrics": lyrics, "lyrics_origin": "human", "duration_seconds": 12, "seed": 100 + index,
            "outputs": ["mix_wav"],
        }, {"Idempotency-Key": f"cycle-gen-{index}"})
        check(f"custom track {index + 1} generated", status == 202)
        detail = wait(accepted["job_id"], f"generation {index + 1}", 300)
        _, artifacts, _ = request("GET", f"/jobs/{accepted['job_id']}/artifacts")
        asset_ids.append(artifacts["artifacts"][0]["asset_id"])

    status, profile, _ = request("POST", "/artist-profiles", {"name": "Cycle Artist",
                                                              "style": {"genre": "country rock"},
                                                              "singer": {"voice": "baritone"}})
    check("profile created", status == 201)
    profile_id = profile["profile_id"]

    status, rights, _ = request("POST", f"/artist-profiles/{profile_id}/rights",
                                {"purpose": "recording", "declaration": "All tracks generated by this owner for training."})
    check("rights declared", status == 201)

    status, dataset, _ = request("POST", f"/artist-profiles/{profile_id}/datasets", {"name": "cycle songs"})
    dataset_id = dataset["dataset_id"]
    for index, asset_id in enumerate(asset_ids):
        status, _, _ = request("POST", f"/datasets/{dataset_id}/tracks",
                               {"asset_id": asset_id, "lyrics": LYRICS[index],
                                "labels": {"caption": PROMPT}})
        check(f"track {index + 1} added", status == 201)

    status, version, _ = request("POST", f"/datasets/{dataset_id}/finalize")
    check("dataset frozen", status == 201 and version["split"]["train"] == 1 and version["split"]["holdout"] == 1,
          f"frozen {version['frozen_sha256'][:12]}…")

    started = time.monotonic()
    status, training, _ = request("POST", "/trainings", {
        "profile_id": profile_id, "dataset_version_id": version["dataset_version_id"],
        "budget": {"max_epochs": 10, "max_wall_seconds": 1800}, "seed": 7,
    }, {"Idempotency-Key": f"cycle-train-{RUN}"})
    check("training queued", status == 202)
    wait(training["job_id"], "LoRA optimization", 1800)
    train_seconds = round(time.monotonic() - started, 1)

    _, runs, _ = request("GET", f"/artist-profiles/{profile_id}/versions")
    candidate = runs[0]
    check("candidate registered", candidate["mechanism"] == "fine_tuned_adapter"
          and candidate["state"] == "candidate" and candidate["artifacts"]["adapter_loadable"] is True,
          f"recipe {candidate['recipe_revision']}")

    started = time.monotonic()
    status, evaluation, _ = request("POST", "/evaluations",
                                    {"profile_version_id": candidate["version_id"], "prompts": [PROMPT]},
                                    {"Idempotency-Key": f"cycle-eval-{RUN}"})
    check("evaluation queued", status == 202)
    wait(evaluation["job_id"], "evaluation", 600)
    eval_seconds = round(time.monotonic() - started, 1)

    profile = request("GET", f"/artist-profiles/{profile_id}")[1]
    status, activated, _ = request("POST", f"/artist-profiles/{profile_id}/activate",
                                   {"version_id": candidate["version_id"]}, {"If-Match": profile["etag"]})
    check("candidate activated", status == 200 and activated["active_version_id"] == candidate["version_id"])

    status, gen, _ = request("POST", "/jobs", {
        "operation": "music.generate", "model_id": "ace-step-1.5", "music_description": PROMPT,
        "lyrics": LYRICS[0], "lyrics_origin": "human", "duration_seconds": 12, "seed": 999,
        "outputs": ["mix_wav"], "artist_profile_version_id": candidate["version_id"],
    }, {"Idempotency-Key": f"cycle-final-{RUN}"})
    check("profile generation queued", status == 202)
    wait(gen["job_id"], "generation with active profile", 300)

    print(f"TIMINGS  training={train_seconds}s  evaluation={eval_seconds}s")
    print("TRAINING CYCLE OK")


if __name__ == "__main__":
    main()
